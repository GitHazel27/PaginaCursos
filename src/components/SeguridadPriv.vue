    <h3>1. Marco de Gestión de la Seguridad</h3>
    <p>La protección de la infraestructura tecnológica y la salvaguarda de los activos digitales de la comunidad estudiantil se gestiona mediante un enfoque de defensa en profundidad. Aplicamos directrices alineadas a los estándares de la familia ISO/IEC 27001 y las mejores prácticas del Open Web Application Security Project (OWASP).</p>
  </section>

  <section class="legal-block">
    <h3>2. Medidas de Seguridad Lógica y Red</h3>
    <p>Nuestros sistemas integran controles de mitigación activos en múltiples capas del entorno tecnológico:</p>
    <ul>
      <li><strong>Cifrado en Tránsito:</strong> Todo tráfico entre el navegador del estudiante y nuestros servidores se cifra obligatoriamente mediante protocolos TLS 1.3 con certificados SSL modernos, forzando cabeceras HSTS (HTTP Strict Transport Security).</li>
      <li><strong>Cifrado en Reposo:</strong> Los volúmenes de almacenamiento de bases de datos y copias de seguridad se encuentran cifrados bajo algoritmos AES-256.</li>
      <li><strong>Gestión Criptográfica de Credenciales:</strong> Las contraseñas nunca se procesan ni almacenan en texto claro; se procesan mediante algoritmos de derivación de claves computacionalmente intensivos (como Argon2id o bcrypt) con factores de salazón únicos por usuario.</li>
      <li><strong>Mitigación de Vulnerabilidades Web:</strong> La plataforma incorpora firewalls de aplicaciones web (WAF) y controles nativos para neutralizar ataques de Inyección SQL, Cross-Site Scripting (XSS), falsificación de peticiones en sitios cruzados (CSRF) y ataques de denegación de servicio distribuido (DDoS).</li>
    </ul>
  </section>

  <section class="legal-block">
    <h3>3. Seguridad en Pasarelas de Pago</h3>
    <p>Para mitigar cualquier vector de fuga de información financiera, los cobros se tramitan mediante mecanismos de tokenización provistos por pasarelas de pago que cuentan con certificación internacional <strong>PCI-DSS Nivel 1</strong>. En ningún momento los números de tarjeta, fechas de caducidad o códigos de seguridad ingresan a los servidores de nuestra aplicación web.</p>
  </section>

  <section class="legal-block">
    <h3>4. Copias de Seguridad y Resiliencia</h3>
    <ul>
      <li><strong>Respaldos Automatizados:</strong> Se ejecutan copias de seguridad incrementales periódicas de bases de datos y contenidos curriculares, las cuales se replican de forma cifrada en centros de datos geográficamente distantes.</li>
      <li><strong>Planes de Recuperación (DRP):</strong> Mantenemos protocolos de recuperación ante desastres y pruebas semestrales de restauración para minimizar el tiempo de inactividad (RTO) y la pérdida potencial de datos (RPO).</li>
    </ul>
  </section>

  <section class="legal-block">
    <h3>5. Gestión de Incidentes de Seguridad</h3>
    <p>Disponemos de un protocolo formal para la detección, contención, análisis y remediación de brechas de seguridad. En el evento imprevisto de una vulneración que comprometa la confidencialidad de datos personales identificables, se notificará a las autoridades correspondientes y a los usuarios afectados en un plazo no mayor a 72 horas tras la confirmación del suceso, detallando la naturaleza del incidente y las acciones de mitigación tomadas.</p>
  </section>

